<?php

if ($this->用户信息 == "定时器测试") {
   $this->发送("文本", "已设置延时30秒\n当前时间：" . date("Y-m-d H:i:s"));
   // 延迟执行（30秒后发送消息）
   $this->定时器("延迟", 30000, function() {
       $this->发送("文本", "30秒后的延迟消息\n当前时间：" . date("Y-m-d H:i:s"));
   });
   
} else if ($this->用户信息 == "循环定时器") {
   $this->发送("文本", "已设置每分钟心跳，发送\"停止循环\"可终止");
   // 循环任务（每分钟执行一次）
   $定时器ID = $this->定时器("循环", 60000, function() {
       echo "[心跳] " . date('Y-m-d H:i:s') . PHP_EOL;
   });
   // 保存定时器ID以便后续清除
   $this->数据库("写", "定时器/{$this->来源ID}", $定时器ID);
   
} else if ($this->用户信息 == "停止循环") {
   $定时器ID = $this->数据库("读", "定时器/{$this->来源ID}");
   if ($定时器ID) {
       $this->定时器("清除", $定时器ID);
       $this->数据库("删", "定时器/{$this->来源ID}");
       $this->发送("文本", "已停止循环定时器");
   } else {
       $this->发送("文本", "没有运行的定时器");
   }
}